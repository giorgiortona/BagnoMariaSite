const TRANSLATIONS = { en: EN, fr: FR }

export function localizeMenuData(menuData, language) {
  const dictionary = TRANSLATIONS[language]
  if (!dictionary) return menuData

  return menuData.map((category) => ({
    ...category,
    categoria: dictionary[category.categoria] || category.categoria,
    nota: category.nota ? (dictionary[category.nota] || category.nota) : undefined,
    piatti: category.piatti.map((item) => ({
      ...item,
      nome: dictionary[item.nome] || item.nome,
      desc: item.desc ? (dictionary[item.desc] || item.desc) : undefined,
    })),
  }))
}
